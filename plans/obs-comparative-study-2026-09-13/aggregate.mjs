import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const expected = ['local', 'royshil', 'tom', 'lars', 'yshk', 'cdavis', 'sbroenne', 'jlfn', 'agentic', 'aaron', 'xdark', 'takurot', 'itchris', 'dcc', 'lhenri', 'sidfou', 'umar', 'giancarlo', 'bea'];
const dimensions = ['A', 'B', 'C', 'D', 'E', 'F'];
const gates = ['G1', 'G2', 'G3', 'G4', 'G5', 'G6'];
const weights = {
  fixed: [25, 20, 15, 15, 15, 10],
  equal: Array(6).fill(100 / 6),
  correctness: [20, 30, 20, 15, 10, 5],
};
const score = (ratings, weighting) => dimensions.reduce((sum, key, i) => sum + ratings[key] * weighting[i] / 4, 0);
const dominates = (a, b) => dimensions.every(key => a[key] >= b[key]) && dimensions.some(key => a[key] > b[key]);
assert.equal(score(Object.fromEntries(dimensions.map(key => [key, 4])), weights.fixed), 100);
assert.equal(dominates({A:4,B:3,C:3,D:3,E:3,F:3}, {A:3,B:3,C:3,D:3,E:3,F:3}), true);
assert.equal(dominates({A:4,B:2,C:3,D:3,E:3,F:3}, {A:3,B:3,C:3,D:3,E:3,F:3}), false);

const records = [];
for (const id of expected) {
  const record = JSON.parse(await readFile(path.join(root, 'candidates', `${id}.json`), 'utf8'));
  assert.equal(record.id, id, `${id}: mismatched identity`);
  for (const key of dimensions) assert.ok(Number.isInteger(record.scores[key]) && record.scores[key] >= 0 && record.scores[key] <= 4, `${id}: invalid score ${key}`);
  for (const key of gates) assert.ok(['P', 'p', 'F', 'NT'].includes(record.gates[key]), `${id}: invalid gate ${key}`);
  records.push({
    ...record,
    totals: Object.fromEntries(Object.entries(weights).map(([name, values]) => [name, Number(score(record.scores, values).toFixed(4))])),
    completeReferenceJobVerified: gates.every(key => record.gates[key] === 'P'),
  });
}
for (const record of records) {
  record.paretoFrontier = !records.some(other => other.id !== record.id && dominates(other.scores, record.scores));
  record.ranks = Object.fromEntries(Object.keys(weights).map(name => [name, 1 + records.filter(other => other.totals[name] > record.totals[name]).length]));
}
records.sort((a, b) => b.totals.fixed - a.totals.fixed || a.id.localeCompare(b.id));
const result = { methodology: 'methodology.md', weights, expectedCandidates: expected, note: 'Architecture ratings are judgments; gates represent finite evidence, not full protocol or real OBS certification.', candidates: records };
await writeFile(path.join(root, 'results', 'rankings.json'), `${JSON.stringify(result, null, 2)}\n`);
let table = '# Comparative score and viability matrix\n\nGenerated by `node aggregate.mjs` from candidate evidence records. Gate order: G1 entry / G2 protocol and identity / G3 state fidelity / G4 failure and lifecycle / G5 reference workflow / G6 honest MCP contract. P = observed pass; p = partial; F = demonstrated failure or missing reference-job capability; NT = not testable. Scores are architecture judgments, separate from viability.\n\n';
table += '| Rank | Candidate | Gates | A | B | C | D | E | F | /100 | Review confidence | Verified complete? | Pareto |\n|---:|---|---|---:|---:|---:|---:|---:|---:|---:|---|---|---|\n';
for (const r of records) table += `| ${r.ranks.fixed} | [${r.id}](candidates/${r.id}.md) | ${gates.map(g => r.gates[g]).join('/')} | ${dimensions.map(d => r.scores[d]).join(' | ')} | ${r.totals.fixed.toFixed(2)} | ${r.confidence ?? 'Unspecified'} | ${r.completeReferenceJobVerified ? 'Yes, fixture scope only' : 'No'} | ${r.paretoFrontier ? 'Yes' : ''} |\n`;
table += '\n## Weight sensitivity\n\n| Candidate | Fixed score / rank | Equal weights score / rank | Correctness-heavy score / rank |\n|---|---:|---:|---:|\n';
for (const r of records) table += `| ${r.id} | ${r.totals.fixed.toFixed(2)} / ${r.ranks.fixed} | ${r.totals.equal.toFixed(2)} / ${r.ranks.equal} | ${r.totals.correctness.toFixed(2)} / ${r.ranks.correctness} |\n`;
table += '\nWeights: fixed A25/B20/C15/D15/E15/F10; equal 1/6 each; correctness-heavy A20/B30/C20/D15/E10/F5. Raw-score Pareto membership ignores gate eligibility. Missing runtime evidence remains visible in gates and confidence rather than being converted into invented behavior.\n';
await writeFile(path.join(root, 'comparison-table.md'), table);
console.log(JSON.stringify({ candidates: records.length, verifiedComplete: records.filter(r => r.completeReferenceJobVerified).map(r => r.id), pareto: records.filter(r => r.paretoFrontier).map(r => r.id) }));
